async def send_question(user_id, question, edit_message=None, is_exam=False):
    user_state = get_user_state(user_id)
    user_state.current_question = question
    user_state.waiting_for_answer = True
    
    if is_exam:
        task_num = user_state.current_exam_index + 1
        header = f"<b>📝 ВАРИАНТ ОГЭ | Задание {task_num}/24</b>\n\n"
    else:
        header = f"<b>🎯 ЗАДАНИЕ №{question['id']}</b>\n\n"
    
    text = f"{header}📚 Тема: {question['topic']}\n⭐ Баллы: {question['points']}\n\n{question['text']}"
    
    if edit_message:
        await edit_message.edit_text(text, reply_markup=get_answer_keyboard(question["id"], question["type"], is_exam))
    else:
        await bot.send_message(user_id, text, reply_markup=get_answer_keyboard(question["id"], question["type"], is_exam))

async def finish_exam(context, user_state):
    if isinstance(context, types.CallbackQuery):
        message = context.message
    else:
        message = context
    
    total = 0
    for q in user_state.current_exam:
        total += q["points"]
    
    accuracy = (user_state.exam_score / total * 100) if total > 0 else 0
    
    if user_state.exam_score >= 35:
        grade = "5 (ОТЛИЧНО)"
    elif user_state.exam_score >= 25:
        grade = "4 (ХОРОШО)"
    elif user_state.exam_score >= 15:
        grade = "3 (УДОВЛ.)"
    else:
        grade = "2 (НЕУД.)"
    
    text = f"""
🏆 <b>ВАРИАНТ ОГЭ ЗАВЕРШЕН!</b>

📊 <b>ИТОГИ:</b>
✅ Баллов: {user_state.exam_score}/{total}
🎯 Точность: {accuracy:.1f}%
📈 Оценка: {grade}

<b>🏅 Достижения:</b>
"""
    if user_state.exam_score >= 25:
        user_state.achievements["oge_master"]["unlocked"] = True
        text += "✅ РАЗБЛОКИРОВАНО: Мастер ОГЭ!\n"
    
    if user_state.perfect_answers_streak >= 10:
        user_state.achievements["perfectionist"]["unlocked"] = True
        text += "✅ РАЗБЛОКИРОВАНО: Перфекционист!\n"
    
    user_state.exam_results.append(user_state.exam_score)
    user_state.current_exam = None
    
    builder = InlineKeyboardBuilder()
    builder.button(text="📊 СТАТИСТИКА", callback_data="stats")
    builder.button(text="🏠 ГЛАВНОЕ МЕНЮ", callback_data="back_main")
    builder.adjust(1)
    
    await message.answer(text, reply_markup=builder.as_markup())

