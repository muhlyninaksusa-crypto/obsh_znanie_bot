# ========== ПРОВЕРКА ТЕКСТОВЫХ ОТВЕТОВ ==========
def check_text_answer(q, ans):
    ans_lower = ans.lower()
    
    # Задание 1 - политические понятия
    if q["id"] == 1:
        return "федерация" in ans_lower and "государство" in ans_lower
    
    # Задание 5 - семья
    elif q["id"] == 5:
        return ("расширен" in ans_lower or "нуклеарн" in ans_lower) and \
               ("эмоц" in ans_lower or "поддерж" in ans_lower or "социализ" in ans_lower)
    
    # Задание 6 - финансы
    elif q["id"] == 6:
        return "мошен" in ans_lower and ("не сообщ" in ans_lower or "пин" in ans_lower or "банк" in ans_lower)
    
    # Задание 12 - диаграмма
    elif q["id"] == 12:
        return "трудов" in ans_lower and "граждан" in ans_lower
    
    # Задание 15 - соответствие
    elif q["id"] == 15:
        return "1" in ans and "2" in ans and len(ans) >= 5
    
    # Задание 19 - сравнение
    elif q["id"] == 19:
        return ("1" in ans and "4" in ans) and ("2" in ans and "3" in ans)
    
    # Задание 20 - таблица
    elif q["id"] == 20:
        return "морал" in ans_lower
    
    # Задание 21 - план
    elif q["id"] == 21:
        return len(ans.split("\n")) >= 3 or len(ans.split(".")) >= 4
    
    # Задание 22 - вопросы по тексту
    elif q["id"] == 22:
        return len(ans.split()) >= 30
    
    # Задание 23 - примеры
    elif q["id"] == 23:
        examples = ["атом", "энерг", "интернет", "ии", "искусствен", "автоматиз"]
        count = sum(1 for ex in examples if ex in ans_lower)
        return count >= 2 and len(ans.split()) >= 40
    
    # Задание 24 - аргументация
    elif q["id"] == 24:
        return len(ans.split()) >= 40 and ("стран" in ans_lower or "развит" in ans_lower)
    
    return False

