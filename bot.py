def get_main_keyboard():
    builder = ReplyKeyboardBuilder()
    buttons = [
        "📚 ТЕОРИЯ", 
        "🎯 ЗАДАНИЯ",
        "📝 ПОЛНЫЙ ОГЭ",
        "🏆 ДОСТИЖЕНИЯ",
        "📊 СТАТИСТИКА",
        "🔄 ПОВТОРИТЬ"
    ]
    for button in buttons:
        builder.add(KeyboardButton(text=button))
    builder.adjust(2, 2, 2)
    return builder.as_markup(resize_keyboard=True)

