def check_text_answer(question, user_answer):
    """Проверка текстового ответа"""
    user_answer_lower = user_answer.lower()
    
    if question["type"] == "concept_explanation":
        # Проверяем наличие правильных понятий
        correct_count = 0
        for correct in question.get("correct_answers", []):
            if any(word.lower() in user_answer_lower for word in correct.lower().split()):
                correct_count += 1
        return correct_count >= 1
    
    elif question["type"] in ["photo_analysis", "diagram_analysis"]:
        # Для заданий с анализом проверяем длину и наличие ключевых слов
        if len(user_answer) > 20:
            return True
        return False
    
    elif question["type"] == "matching":
        # Проверяем формат соответствий
        if "-" in user_answer:
            return True
        return False
    
    elif question["type"] == "comparison":
        # Проверяем наличие слов "сход" или "различ"
        if any(word in user_answer_lower for word in ["сход", "similar", "различ", "diff", "отлич"]):
            return True
        return False
    
    elif question["type"] == "table_fill":
        correct_answer = question.get("correct", "").lower()
        if correct_answer and correct_answer in user_answer_lower:
            return True
        return False
    
    elif question["type"] in ["text_plan", "text_questions", "examples", "argumentation"]:
        # Для текстовых заданий проверяем развернутость ответа
        if len(user_answer) > 30:
            return True
        return False
    
    # Для остальных типов считаем правильным
    return True

async def finish_exam(context, user_state):
    """Завершение экзамена и вывод результатов"""
    if isinstance(context, types.CallbackQuery):
        message = context.message
    else:
        message = context
    
    total_points_possible = 0
    for question in user_state.current_exam:
        total_points_possible += question["points"]
    
    accuracy = (user_state.exam_score / total_points_possible * 100) if total_points_possible > 0 else 0
    
    # Определяем оценку
    if user_state.exam_score >= 35:
        grade = "5 (ОТЛИЧНО)"
        grade_emoji = "🏆"
    elif user_state.exam_score >= 25:
        grade = "4 (ХОРОШО)"
        grade_emoji = "⭐"
    elif user_state.exam_score >= 15:
        grade = "3 (УДОВЛЕТВОРИТЕЛЬНО)"
        grade_emoji = "✅"
    else:
        grade = "2 (НЕУДОВЛЕТВОРИТЕЛЬНО)"
        grade_emoji = "❌"
    
    result_text = f"""
{grade_emoji} <b>ВАРИАНТ ОГЭ ЗАВЕРШЕН!</b> {grade_emoji}

📊 <b>ИТОГОВЫЙ РЕЗУЛЬТАТ:</b>
✅ Набрано баллов: {user_state.exam_score}/{total_points_possible}
🎯 Точность: {accuracy:.1f}%
📈 Оценка: {grade}

<b>📖 РАСПРЕДЕЛЕНИЕ ПО ТЕМАМ:</b>
"""
    
    # Статистика по темам в экзамене
    if user_state.exam_topic_stats:
        for topic, stats in user_state.exam_topic_stats.items():
            if stats["total"] > 0:
                topic_accuracy = (stats["points"] / (stats["total"] * 2)) * 100
                result_text += f"\n• <b>{topic}:</b> {stats['points']}/{stats['total']*2} баллов ({topic_accuracy:.0f}%)"
    
    result_text += f"""

<b>📝 АНАЛИЗ РЕЗУЛЬТАТА:</b>
"""
    
    if accuracy >= 80:
        result_text += "🎉 Отличный результат! Вы хорошо подготовлены к экзамену."
        # Проверяем достижение "Мастер ОГЭ"
        if user_state.exam_score >= 25:
            user_state.achievements["oge_master"]["unlocked"] = True
            result_text += "\n🏆 <b>ДОСТИЖЕНИЕ РАЗБЛОКИРОВАНО: Мастер ОГЭ!</b>"
    elif accuracy >= 60:
        result_text += "👍 Хороший результат. Обратите внимание на сложные для вас темы."
    elif accuracy >= 40:
        result_text += "📚 Нужно больше практики. Повторите теорию по слабым темам."
    else:
        result_text += "📖 Требуется серьезная подготовка. Начните с повторения базовой теории."
    
    # Рекомендации
    weak_topics = user_state.get_weak_topics(2)
    if weak_topics:
        result_text += f"\n\n<b>🎯 РЕКОМЕНДАЦИИ:</b>\n"
        for topic in weak_topics:
            result_text += f"• Повторите тему <b>{topic['topic']}</b> (точность: {topic['accuracy']:.1f}%)\n"
    
    result_text += f"""

📈 <b>Ваш прогресс:</b>
• Пройдено вариантов: {len(user_state.exam_results) + 1}
• Лучший результат: {max(user_state.exam_results + [user_state.exam_score])}/{total_points_possible}
"""
    
    # Сохраняем результат
    user_state.exam_results.append(user_state.exam_score)
    user_state.current_exam = None
    user_state.current_exam_index = 0
    
    keyboard = InlineKeyboardBuilder()
    keyboard.button(text="🔄 ПОВТОРИТЬ СЛАБЫЕ ТЕМЫ", callback_data="repeat_weak")
    keyboard.button(text="📊 СТАТИСТИКА", callback_data="stats")
    keyboard.button(text="🏠 ГЛАВНОЕ МЕНЮ", callback_data="back_main")
    keyboard.adjust(1)
    
    await message.answer(result_text, parse_mode="HTML", reply_markup=keyboard.as_markup())

